-- 압생트 린스를 쓰는 칵테일 2건의 제조순서 교정.
--
-- 425종 적재분 중 제조순서가 기계로 생성된 것들이 있는데, 그 템플릿은 재료를
-- "넣고 섞는 것"으로만 다룬다. 린스(rinse)는 잔 안쪽을 적시고 남은 술을 버리는
-- 기법이라 이 틀에 맞지 않는다. 그래서 두 건이 압생트를 셰이커나 믹싱 글라스에
-- 넣으라고 안내하고 있었다. 그대로 따라 하면 다른 술이 나온다.
--
--   325 마카라          압생트를 믹싱 글라스에 넣고 저으라고 안내
--   372 뉴올리언스 버번  사제락인데 압생트를 셰이커에 넣고 흔들라고 안내.
--                       사제락은 젓는 술이고, 얼음 없이 낸다.
--
-- 재료 원문도 함께 고친다. 372 는 "압생트 린스 린스(약간)" 로 단어가 겹쳐 있었고,
-- 325 는 "압생트 약간 린스(약간)" 로 수량과 기법이 뒤엉켜 있었다.

UPDATE cocktail
SET ingredients_text = '진 45ml (1½ oz), 드라이 베르무트 20ml (⅔ oz), 오렌지 큐라소 15ml (½ oz), 압생트 린스(약간)',
    updated_at = CURRENT_TIMESTAMP
WHERE id = 325;

UPDATE cocktail
SET ingredients_text = '버번 45ml (1½ oz), 페이쇼드 비터스 2 dashes, 설탕 1 tsp, 압생트 린스(약간)',
    updated_at = CURRENT_TIMESTAMP
WHERE id = 372;

DELETE FROM cocktail_step WHERE cocktail_id IN (325, 372);

