SET image_url = image_url || '?v=2',
    updated_at = CURRENT_TIMESTAMP
WHERE id IN (109, 116, 130, 131, 135, 141, 147, 150, 151, 152, 153, 155, 156, 157, 163, 169, 170, 171, 172, 173, 174, 175, 184, 190, 195, 204, 208, 211, 216, 225, 232, 234, 239, 241, 243, 251, 252, 253, 254, 256, 258, 261, 262, 267, 275, 280, 282, 288, 294, 306, 310, 311, 314, 316, 323, 326, 332, 342, 344, 347, 349, 354, 363, 378, 394, 396, 397, 398, 405, 413, 420, 424, 431, 432, 434, 436, 439, 445, 446, 450, 451, 458, 459, 461, 470, 471, 472, 480, 485, 490, 491, 512, 514, 516, 518, 522, 524, 526, 527)
  AND image_url NOT LIKE '%?v=%';
