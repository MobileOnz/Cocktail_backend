-- 교체한 칵테일 이미지 99종의 캐시를 깨뜨린다.
--
-- 이미지 파일은 서버에서 같은 이름으로 갈아끼웠다(구도·배경이 더 나은 판으로).
-- 그런데 nginx 가 /uploads/ 를 `Cache-Control: public, immutable, max-age=2592000`
-- 으로 내려준다. immutable 이라 기기는 30일 동안 재검증조차 하지 않는다.
-- URL 이 그대로면 이미 앱을 켜본 사람에게는 예전 이미지가 계속 보인다.
--
-- 그래서 URL 에 버전을 붙인다. 파일명을 바꾸지 않는 이유는 서버에 이미 올라간
-- 파일과 백업(_replaced_*)의 짝을 유지하기 위해서다. nginx 는 쿼리스트링을
-- 무시하고 같은 파일을 내주므로 서빙에는 영향이 없다(확인함).
--
-- 다음에 또 같은 이름으로 교체하면 v=3 으로 올린다.

